import re


def ref(number, label=""):
    """Return a compact, in-text link to an article reference."""
    text = str(number)
    if label:
        text += f"，{label}"
    return (
        f'<sup class="source-citation">[<a href="#ref-{number}">{text}</a>]</sup>'
    )


def copy(title, summary, body):
    # Expand citation markers after the triple-quoted HTML has been authored.
    body = re.sub(
        r'\$\{ref\((\d+),\s*"([^"]*)"\)\}',
        lambda match: ref(int(match.group(1)), match.group(2)),
        body,
    )
    body = re.sub(
        r'\$\{ref\((\d+)\)\}',
        lambda match: ref(int(match.group(1))),
        body,
    )
    return {"title": title, "summary": summary, "body": body}


